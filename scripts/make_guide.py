"""Write the command reference at the end of docs/GUIDE.md from the CLI's own parser.

    python scripts/make_guide.py          # rewrite the reference in place
    python scripts/make_guide.py --check  # exit 1 if it is out of date (tests/test_docs.py runs this check)

Only the part between the two reference markers is generated; everything above them is written by hand.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

GUIDE = ROOT / "docs" / "GUIDE.md"
START = "<!-- reference:start (generated by scripts/make_guide.py; do not edit by hand) -->"
END = "<!-- reference:end -->"


def _cell(s: str) -> str:
    return " ".join(str(s).split()).replace("|", "\\|")


def _option_rows(p: argparse.ArgumentParser) -> list[str]:
    rows = []
    for a in p._actions:
        if isinstance(a, (argparse._HelpAction, argparse._SubParsersAction)):
            continue
        if a.option_strings:
            name = ", ".join(f"`{o}`" for o in a.option_strings)
            if a.nargs != 0 and a.metavar:
                name += f" `{a.metavar}`"
            elif a.nargs != 0 and a.choices:
                name += " `" + "\\|".join(str(c) for c in a.choices) + "`"
        else:
            name = f"`{a.metavar or a.dest}`" + ("" if a.nargs not in ("?", "*") else " (optional)")
        default = ""
        if a.option_strings and a.nargs != 0 and a.default not in (None, [], "", argparse.SUPPRESS):
            default = f"`{a.default}`"
        rows.append(f"| {name} | {default} | {_cell(a.help or '')} |")
    return rows


def _commands(p: argparse.ArgumentParser, prefix: str) -> list[tuple[str, str, argparse.ArgumentParser]]:
    out = []
    for a in p._actions:
        if isinstance(a, argparse._SubParsersAction):
            helps = {c.dest: c.help for c in a._choices_actions}
            for name, sub in a.choices.items():
                out.append((f"{prefix} {name}", helps.get(name) or "", sub))
                out += _commands(sub, f"{prefix} {name}")
    return out


def reference() -> str:
    from wsr.cli import build_parser

    lines = [START, "", "## Command reference", "",
             "Every command and option, as `wsr <command> --help` prints them.", ""]
    for name, help_, sub in _commands(build_parser(), "wsr"):
        rows = _option_rows(sub)
        has_sub = any(isinstance(a, argparse._SubParsersAction) for a in sub._actions)
        if has_sub and not rows:
            continue
        lines += [f"### `{name}`", ""]
        if help_:
            lines += [_cell(help_)[0].upper() + _cell(help_)[1:] + ("" if help_.rstrip().endswith(".") else "."), ""]
        if rows:
            lines += ["| Option | Default | What it does |", "|---|---|---|", *rows, ""]
    return "\n".join(lines + [END])


def main() -> int:
    text = GUIDE.read_text(encoding="utf-8")
    if START not in text or END not in text:
        print(f"{GUIDE}: the reference markers are missing", file=sys.stderr)
        return 1
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    new = head + reference() + tail
    if "--check" in sys.argv[1:]:
        if new != text:
            print("docs/GUIDE.md's command reference is out of date: run python scripts/make_guide.py",
                  file=sys.stderr)
            return 1
        return 0
    GUIDE.write_text(new, encoding="utf-8", newline="\n")
    print(f"wrote the command reference in {GUIDE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
